/**
 * 生成 TypeScript/Config/Env/config.active.ts.
 *
 * 用法:
 *   node Scripts/select-config-profile.mjs --profile=Development
 *   APP_ENV=Shipping node Scripts/select-config-profile.mjs
 */

import fs from 'node:fs';
import path from 'node:path';

const PROFILE_DEFINITIONS = {
    Development: {
        modulePath: './config.dev',
        exportName: 'configDev',
    },
    QA: {
        modulePath: './config.qa',
        exportName: 'configQa',
    },
    Shipping: {
        modulePath: './config.shipping',
        exportName: 'configShipping',
    },
};

const projectRoot = process.cwd();
const configDir = path.resolve(projectRoot, 'TypeScript/Config/Env');
const activeFile = path.join(configDir, 'config.active.ts');
const devFile = path.join(configDir, 'config.dev.ts');
const devExampleFile = path.join(configDir, 'config.dev.example.ts');

function readArg(name) {
    const prefix = `--${name}=`;
    const value = process.argv.slice(2).find((arg) => arg.startsWith(prefix));
    return value ? value.slice(prefix.length) : undefined;
}

function normalizeProfile(value) {
    const raw = value || process.env.APP_ENV || process.env.NODE_ENV || 'Development';
    const normalized = raw.toLowerCase();
    if (normalized === 'dev' || normalized === 'development') {
        return 'Development';
    }
    if (normalized === 'qa' || normalized === 'test' || normalized === 'testing') {
        return 'QA';
    }
    if (normalized === 'ship' || normalized === 'shipping' || normalized === 'production' || normalized === 'prod') {
        return 'Shipping';
    }

    console.error(`[select-config-profile] unsupported profile: ${raw}`);
    console.error(`[select-config-profile] expected one of: ${Object.keys(PROFILE_DEFINITIONS).join(', ')}`);
    process.exit(1);
}

function ensureDevelopmentConfig() {
    if (fs.existsSync(devFile)) {
        return;
    }
    if (!fs.existsSync(devExampleFile)) {
        console.error(`[select-config-profile] missing ${path.relative(projectRoot, devExampleFile)}`);
        process.exit(1);
    }

    fs.copyFileSync(devExampleFile, devFile);
    console.log(`[select-config-profile] created ${path.relative(projectRoot, devFile)} from config.dev.example.ts`);
}

function assertProfileModuleExists(profile, definition) {
    const moduleFile = path.resolve(configDir, `${definition.modulePath.slice(2)}.ts`);
    if (!fs.existsSync(moduleFile)) {
        console.error(`[select-config-profile] ${profile} config missing: ${path.relative(projectRoot, moduleFile)}`);
        process.exit(1);
    }
}

const profile = normalizeProfile(readArg('profile'));
const definition = PROFILE_DEFINITIONS[profile];

if (profile === 'Development') {
    ensureDevelopmentConfig();
}
assertProfileModuleExists(profile, definition);

const source = `/**
 * 当前构建选中的运行时配置 profile.
 *
 * Auto-generated by Scripts/select-config-profile.mjs. Do not edit.
 */
import type { AppEnvironment } from './config.default';
import { ${definition.exportName} } from '${definition.modulePath}';

export const activeConfigProfile: AppEnvironment = '${profile}';
export const configActive = ${definition.exportName};
`;

fs.writeFileSync(activeFile, source, 'utf8');
console.log(`[select-config-profile] ${path.relative(projectRoot, activeFile)} -> ${profile}`);
