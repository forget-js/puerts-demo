/**
 * 生成 mixin-imports.{shared,client,server}.ts 聚合 import。
 *
 * 优先使用 Manifest 中的 autoManaged mixin 列表与 executionContext 分端输出;
 * Manifest 不存在时回退扫描 MixinSourceRoot (全部写入 shared).
 *
 * 用法: node generate-mixin-index.mjs --project=<项目根> --mixin-root=... --index=...
 */
import fs from 'node:fs';
import path from 'node:path';
import {
  EXECUTION_CONTEXTS,
  loadManifest,
  normalizeExecutionContext,
  normalizeProjectRelativePath,
  saveCatalog,
  toProjectPath,
} from './blueprint-manifest-utils.mjs';

const args = process.argv.slice(2);

/** 从命令行读取 --name=value 参数 */
function readArg(name, fallback) {
  const prefix = `--${name}=`;
  const value = args.find((arg) => arg.startsWith(prefix));
  return value ? value.slice(prefix.length) : fallback;
}

const projectRoot = path.resolve(readArg('project', process.cwd()));
const mixinRoot = path.resolve(projectRoot, readArg('mixin-root', 'TypeScript/Mixins/Blueprints'));
const indexFile = path.resolve(projectRoot, readArg('index', 'TypeScript/Mixins/_generated/mixin-imports.ts'));
const manifestFile = toProjectPath(projectRoot, readArg('manifest', 'TypeScript/Mixins/_generated/blueprint-manifest.json'));
const catalogFile = toProjectPath(projectRoot, readArg('catalog', 'TypeScript/Blueprints/_generated/BlueprintCatalog.ts'));

/** 递归收集目录下所有 .ts 文件（排除 .d.ts） */
function walk(dir) {
  if (!fs.existsSync(dir)) {
    return [];
  }

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  return entries.flatMap((entry) => {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      return walk(entryPath);
    }
    if (entry.isFile() && entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts')) {
      return [entryPath];
    }
    return [];
  });
}

function toImportPath(indexDir, file) {
  let importPath = path.relative(indexDir, file).replace(/\\/g, '/').replace(/\.ts$/, '');
  if (!importPath.startsWith('.')) {
    importPath = `./${importPath}`;
  }
  return importPath;
}

/** 取得应被副作用 import 的 mixin 文件列表 (含 executionContext). */
function getMixinEntries(manifest) {
  if (!fs.existsSync(manifestFile)) {
    return walk(mixinRoot).map((file) => ({
      file,
      executionContext: 'Shared',
    }));
  }

  saveCatalog(catalogFile, manifest);
  return manifest.blueprints
    .filter((entry) => !entry.missing && entry.autoManaged !== false)
    .map((entry) => ({
      file: toProjectPath(projectRoot, normalizeProjectRelativePath(entry.mixinFile)),
      executionContext: normalizeExecutionContext(entry.executionContext),
    }))
    .filter(({ file }) => fs.existsSync(file));
}

function makeIndexSource(indexDir, entries) {
  const imports = entries
    .sort((a, b) => a.file.localeCompare(b.file))
    .map(({ file }) => `import "${toImportPath(indexDir, file)}";`);

  return [
    '// Auto-generated by PuertsMixinAutomation. Do not edit.',
    ...imports,
    '',
  ].join('\n');
}

const manifest = loadManifest(manifestFile);
const mixinEntries = getMixinEntries(manifest);
const indexDir = path.dirname(indexFile);

fs.mkdirSync(indexDir, { recursive: true });

for (const context of EXECUTION_CONTEXTS) {
  const contextEntries = mixinEntries.filter(
    (entry) => normalizeExecutionContext(entry.executionContext) === context
  );
  const contextFile = path.join(indexDir, `mixin-imports.${context.toLowerCase()}.ts`);
  fs.writeFileSync(contextFile, makeIndexSource(indexDir, contextEntries), 'utf8');
}

// 兼容旧工具链: 全量索引 (register.ts 已按 NetRole 分端加载, 此文件仅供对照/迁移).
const legacySource = makeIndexSource(indexDir, mixinEntries);
fs.writeFileSync(indexFile, legacySource, 'utf8');
